import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, "..")
const jsonPath = path.join(
  root,
  "contracts/out/MinimalLabToken.sol/MinimalLabToken.json",
)
const j = JSON.parse(fs.readFileSync(jsonPath, "utf8"))
const dir = path.join(root, "lib/liquidity-lab")
fs.mkdirSync(dir, { recursive: true })
const out = path.join(dir, "minimal-lab-token.generated.ts")
const body = `// Auto-generated by scripts/generate-minimal-token-artifact.mjs (run \`forge build\` in contracts/ first)
export const MINIMAL_LAB_TOKEN_BYTECODE = ${JSON.stringify(j.bytecode.object)} as const
export const MINIMAL_LAB_TOKEN_ABI = ${JSON.stringify(j.abi)} as const
`
fs.writeFileSync(out, body)
console.log("Wrote", out, body.length, "bytes")
